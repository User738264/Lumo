using Lumo.Parsing.IntegrationTests.Helpers;

using Xunit;

namespace Lumo.Parsing.IntegrationTests;

public class RuntimeErrorTests
{
    public static TheoryData<string, string, string> FailingExpressions()
    {
        return new TheoryData<string, string, string>
        {
            // Деление и взятие остатка при делителе, равном нулю.
            { "1 / 0", "", "Строка 3, столбец 3: деление на ноль" },
            { "1 % 0", "", "Строка 3, столбец 3: деление на ноль" },

            // Результат арифметической операции вне диапазона типа int.
            { "9223372036854775807 + 1", "", "Строка 3, столбец 21: целочисленное переполнение" },
            { "(-9223372036854775807 - 1) - 1", "", "Строка 3, столбец 28: целочисленное переполнение" },
            { "9223372036854775807 * 2", "", "Строка 3, столбец 21: целочисленное переполнение" },
            { "(-9223372036854775807 - 1) / -1", "", "Строка 3, столбец 28: целочисленное переполнение" },
            { "-(-9223372036854775807 - 1)", "", "Строка 3, столбец 1: целочисленное переполнение" },

            // Поток ввода исчерпан.
            { "read_int()", "", "Строка 3, столбец 1: поток ввода исчерпан" },

            // Строка ввода не является десятичной записью целого числа.
            { "read_int()", "   ", "Строка 3, столбец 1: ожидается десятичная запись целого числа" },
            { "read_int()", "+", "Строка 3, столбец 1: ожидается десятичная запись целого числа" },
            { "read_int()", "- 5", "Строка 3, столбец 1: ожидается десятичная запись целого числа" },
            { "read_int()", "\v5", "Строка 3, столбец 1: ожидается десятичная запись целого числа" },
            { "read_int()", "1.5", "Строка 3, столбец 1: ожидается десятичная запись целого числа" },
            { "read_int()", "abc", "Строка 3, столбец 1: ожидается десятичная запись целого числа" },
            { "read_int()", "5\0", "Строка 3, столбец 1: ожидается десятичная запись целого числа" },

            // Число в строке ввода вне диапазона типа int.
            { "read_int()", "9223372036854775808", "Строка 3, столбец 1: ожидается целое число в диапазоне int" },
        };
    }

    [Theory]
    [MemberData(nameof(FailingExpressions))]
    public void Stops_on_runtime_error_and_keeps_earlier_output(string expression, string input, string expectedError)
    {
        string source = "func main() {\nprint_int(7);\n" + expression + ";\nprint_int(9);\n}";

        CliResult result = CliRunner.RunProgram(source, input);

        Assert.Equal(CliResult.Failure("7\n", expectedError), result);
    }
}